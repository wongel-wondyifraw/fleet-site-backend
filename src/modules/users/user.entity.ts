// @Exclude prevents passwordHash from appearing in serialized API responses.
import { Exclude } from 'class-transformer';
// TypeORM decorators define the database table mapping.
import {
  Column,
  CreateDateColumn,
  Entity,
  Index,
  JoinTable,
  ManyToMany,
  PrimaryGeneratedColumn,
  UpdateDateColumn,
} from 'typeorm';

// UserRole enum stored as a varchar column.
import { UserRole } from '../../common/enums';
// Site entity for the many-to-many assignment relationship.
import { Site } from '../sites/site.entity';

// Maps to the "users" table in PostgreSQL.
@Entity({ name: 'users' })
// Composite index speeds up name-based searches in findAll.
@Index(['lastName', 'firstName'])
export class User {
  // UUID primary key generated by Postgres.
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  // Unique login identifier; stored lowercase by the service layer.
  @Column({ type: 'varchar', unique: true })
  email!: string;

  // bcrypt hash; never returned to clients thanks to @Exclude below.
  @Exclude()
  @Column({ type: 'varchar' })
  passwordHash!: string;

  // Display / profile fields.
  @Column({ type: 'varchar' })
  firstName!: string;

  @Column({ type: 'varchar' })
  lastName!: string;

  // Role determines what the RolesGuard allows; default TIME_KEEPER.
  @Column({ type: 'varchar', length: 32, default: UserRole.TIME_KEEPER })
  role!: UserRole;

  // Soft-delete flag; deactivated users cannot log in.
  @Column({ type: 'boolean', default: true })
  isActive!: boolean;

  // Updated on each successful login by UsersService.recordLogin().
  @Column({ type: 'timestamptz', nullable: true })
  lastLoginAt?: Date | null;

  // Many-to-many: a user can be assigned to multiple sites.
  @ManyToMany(() => Site, (site) => site.users)
  // Join table "user_sites" with explicit column names for clarity in SQL.
  @JoinTable({
    name: 'user_sites',
    joinColumn: { name: 'userId', referencedColumnName: 'id' },
    inverseJoinColumn: { name: 'siteId', referencedColumnName: 'id' },
  })
  sites!: Site[];

  // Auto-managed creation timestamp.
  @CreateDateColumn()
  createdAt!: Date;

  // Auto-managed last-update timestamp.
  @UpdateDateColumn()
  updatedAt!: Date;
}
